/**
 * Writes dist/_headers for Cloudflare Pages.
 *
 * Why this is generated rather than committed: the Content-Security-Policy has
 * to name the exact Supabase origin the bundle will talk to, and that origin
 * differs per environment. Production deployments point at the live project;
 * preview deployments point at the UAT one. A committed _headers file would
 * name one of them and silently block the other, which shows up as a login
 * that hangs with a console error nobody reads.
 *
 * So the origin comes from the same VITE_SUPABASE_URL that Vite inlined into
 * the bundle, which means the policy and the code can never disagree.
 *
 *   npx tsx scripts/generate-headers.ts
 *
 * It runs as the last step of `npm run build`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const DIST = resolve(ROOT, 'dist');

function parseEnvFile(path: string): Record<string, string> {
  if (!existsSync(path)) return {};
  const values: Record<string, string> = {};
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('#')) continue;
    const index = trimmed.indexOf('=');
    if (index === -1) continue;
    values[trimmed.slice(0, index).trim()] = trimmed
      .slice(index + 1)
      .trim()
      .replace(/^["']|["']$/g, '');
  }
  return values;
}

/**
 * The Supabase origin, from the environment Vite built with. On Cloudflare
 * Pages this comes from the project's environment variables; locally it comes
 * from .env (or .env.uat when built with --mode uat).
 */
function supabaseOrigin(): string {
  // `--mode uat` matches the flag Vite was given, so the two read the same file.
  const flag = process.argv.indexOf('--mode');
  const mode = flag === -1 ? 'production' : (process.argv[flag + 1] ?? 'production');
  const fromProcess = process.env.VITE_SUPABASE_URL;
  const fromFile =
    mode === 'production'
      ? parseEnvFile(resolve(ROOT, '.env')).VITE_SUPABASE_URL
      : parseEnvFile(resolve(ROOT, `.env.${mode}`)).VITE_SUPABASE_URL;

  const raw = fromProcess ?? fromFile;
  if (raw === undefined || raw.trim() === '') {
    throw new Error(
      'VITE_SUPABASE_URL is not set, so the Content-Security-Policy cannot name ' +
        'the Supabase origin. Set it in the environment or in .env.',
    );
  }
  return new URL(raw.trim()).origin;
}

function websocketOrigin(httpsOrigin: string): string {
  return httpsOrigin.replace(/^https:/, 'wss:').replace(/^http:/, 'ws:');
}

function contentSecurityPolicy(origin: string): string {
  return [
    // Everything falls back to same-origin; the directives below only widen
    // what genuinely has to be wider.
    `default-src 'self'`,

    // Stated explicitly even though default-src already covers it: without it
    // Chrome logs "Note that 'script-src' was not explicitly set" on every page
    // load, which pilot users reasonably report as an error. The Vite build
    // emits no inline scripts, so 'self' is the whole policy.
    `script-src 'self'`,

    // Supabase: REST, Auth and the invite-agents Edge Function all live on the
    // project origin, and Realtime (if ever enabled) uses the wss one.
    `connect-src 'self' ${origin} ${websocketOrigin(origin)}`,

    // data: is for the favicon and any inline SVG data URI.
    `img-src 'self' data:`,

    // 'unsafe-inline' is needed, and only for styles. The Radix primitives
    // (Dialog, DropdownMenu, Tooltip) position themselves by writing into the
    // element's style attribute at runtime, and scroll-locking the body does
    // the same. CSP has no nonce mechanism for style ATTRIBUTES, so there is no
    // stricter policy that leaves those components working. Tailwind itself
    // compiles to a stylesheet file and needs nothing. Scripts stay strict
    // under default-src 'self', which is where the real risk is.
    `style-src 'self' 'unsafe-inline'`,

    // Inter is bundled by @fontsource-variable/inter and served from /assets,
    // so no font CDN is involved.
    `font-src 'self'`,

    // Nothing embeds this app, and it embeds nothing.
    `frame-ancestors 'none'`,
    `frame-src 'none'`,
    `object-src 'none'`,

    `base-uri 'self'`,
    `form-action 'self'`,
    `upgrade-insecure-requests`,
  ].join('; ');
}

function headersFile(origin: string): string {
  const csp = contentSecurityPolicy(origin);

  return `# GENERATED by scripts/generate-headers.ts - do not edit dist/_headers by hand.
# The Supabase origin below came from the VITE_SUPABASE_URL this bundle was
# built with: ${origin}

/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin

# Vite fingerprints every file in /assets, so a changed file gets a new name.
# That makes them safe to cache forever, which is most of the speed on a slow
# connection.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# index.html must never be cached: it is what points at the current asset
# names, so a stale copy would load a deployment that no longer exists.
/index.html
  Cache-Control: no-cache, must-revalidate

/
  Cache-Control: no-cache, must-revalidate
`;
}

function main(): void {
  if (!existsSync(DIST)) {
    console.error('No dist/ to write _headers into. Run `vite build` first.');
    process.exitCode = 1;
    return;
  }

  const origin = supabaseOrigin();
  const path = resolve(DIST, '_headers');
  writeFileSync(path, headersFile(origin), 'utf8');

  console.log(`Wrote dist/_headers with connect-src for ${origin}`);
}

main();
